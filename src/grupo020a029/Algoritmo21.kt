package algoritmos.grupo020a029.algoritmo21

import kotlin.math.*

fun main() {
    println("TESTANDO HIERARQUIA")
    println("12 + 5 / 2 = ${12 + 5.0 / 2}")
    println("(12 + 5) / 2 = ${(12 + 5) / 2.0}")
    println("64 ** 1 / 4 = ${64.0.pow(1) / 4}")
    println("64 ** (1 / 4) = ${64.0.pow(1.0 / 4)}")
    println("3 * 7 % 5 no UAL = ${3 * (7 % 5)}")
    println("(3 * 7) % 5 = ${(3 * 7) % 5}")
    println("3 * 7 div 5 = ${3 * 7 / 5}")
    println("(3 * 7) div 5 = ${(3 * 7) / 5}")
}
